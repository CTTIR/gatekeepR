test_that("app decisions use review APIs and invalidate older snapshots", {
  skip_if_not_installed("shiny")
  skip_if_not_installed("dbscan")
  review <- gk_app_test_review()
  app <- gk_app(review = review)
  shiny::testServer(app$serverFuncSource(), {
    session$setInputs(image = "img-1", cut_marker = "A", cut_estimate = 60,
      reviewer = "", reason = "", snapshot_status = "PENDING")
    session$setInputs(set_cut = 1)
    expect_equal(nrow(current_review()$ledgers$cut_log), 0L)
    expect_match(action_status(), "Decision not applied")
    session$setInputs(reviewer = "Reviewer One", reason = "Review of marker distribution", set_cut = 2)
    expect_equal(effective()$thresholds$estimate, 60)
    expect_equal(sum(effective()$cells$pending_review), 41L)
    expect_match(output$overview, "Cells: 100")
    expect_match(output$overview, "Ledger entries: 1")
    session$setInputs(lock_snapshot = 1)
    expect_s3_class(locked_snapshot(), "gk_snapshot")
    expect_identical(locked_snapshot()$status, "PENDING")
    expect_false(locked_snapshot()$production_eligible)
    session$setInputs(structure_mode = "BBOX", structure_xmin = 60, structure_xmax = 100,
      structure_ymin = 0, structure_ymax = 2, structure_decision = "Tumor", set_structure = 1)
    expect_null(locked_snapshot())
    expect_equal(sum(effective()$cells$cell_type == "Tumor"), 41L)
    expect_equal(nrow(current_review()$ledgers$structure_log), 1L)
    session$setInputs(state_marker = "S", state_parent = "Tumor", state_action = "SET_CUT",
      state_estimate = 90, set_state = 1)
    session$setInputs(state_action = "ENABLE", set_state = 2)
    expect_true(all(effective()$state_calls$enabled))
    expect_true(all(effective()$state_calls$estimate == 90))
    expect_equal(sum(effective()$state_calls$positive), 11L)
    session$setInputs(disposition_mode = "ID", cell_id = "c0100", disposition = "EXCLUDE", set_disposition = 1)
    expect_false(effective()$cells$analysed[100])
    session$setInputs(disposition = "DELETE", set_disposition = 2)
    expect_identical(effective()$cells$disposition_effective[100], "DELETE")
    session$setInputs(revert = 1)
    expect_identical(effective()$cells$disposition_effective[100], "EXCLUDE")
    expect_equal(nrow(current_review()$ledgers$disposition_log), 3L)
    session$setInputs(snapshot_status = "REVIEWED", confirm_reviewed = FALSE, lock_snapshot = 2)
    expect_null(locked_snapshot())
    expect_match(action_status(), "Confirm the completed review")
    session$setInputs(confirm_reviewed = TRUE, lock_snapshot = 3)
    expect_identical(locked_snapshot()$status, "REVIEWED")
    expect_true(locked_snapshot()$production_eligible)
    expect_match(output$ledger, "EXCLUDE")
  })
  expect_true(all(vapply(gk_ledgers(review), nrow, integer(1)) == 0L))
})

test_that("app checkpoints save explicitly, retain revisions and reject stale writers", {
  skip_if_not_installed("shiny")
  skip_if_not_installed("dbscan")
  dir <- tempfile("app-checkpoint-")
  on.exit(unlink(dir, recursive = TRUE))
  app <- gk_app(review = gk_app_test_review(), workdir = dir)
  expect_false(dir.exists(dir))
  shiny::testServer(app$serverFuncSource(), {
    session$setInputs(image = "img-1", reviewer = "Reviewer One", reason = "Checkpoint test",
      cut_marker = "A", cut_estimate = 60)
    session$setInputs(save_checkpoint = 1)
    expect_match(action_status(), "Checkpoint saved")
    expect_match(current_review()$checkpoint_revision, "^[a-f0-9]{64}$")
    session$setInputs(set_cut = 1, save_checkpoint = 2)
    expect_match(action_status(), "Checkpoint saved")
    expect_equal(gk_replay(gk_load_review(dir))$thresholds$estimate, 60)
    other <- gk_load_review(dir)
    other <- gk_set_cut(other, "img-1", "A", estimate = 70, reviewer = "Reviewer Two", reason = "Newer independent decision")
    gk_save_review(other, dir, overwrite = TRUE)
    session$setInputs(save_checkpoint = 3)
    expect_match(action_status(), "changed|stale|newer")
    expect_equal(gk_replay(gk_load_review(dir))$thresholds$estimate, 70)
  })
  # A second browser session on the same app object must not reuse the
  # original, revision-free in-memory review after the first browser closes.
  shiny::testServer(app$serverFuncSource(), {
    session$setInputs(image = "img-1")
    expect_equal(effective()$thresholds$estimate, 70)
    expect_match(current_review()$checkpoint_revision, "^[a-f0-9]{64}$")
    session$setInputs(save_checkpoint = 1)
    expect_match(action_status(), "Checkpoint saved")
    expect_equal(gk_replay(gk_load_review(dir))$thresholds$estimate, 70)
  })
  expect_error(gk_app(review = gk_app_test_review(), workdir = dir), "existing workdir")
  expect_true(shiny::is.shiny.appobj(gk_app(workdir = dir)))
})

test_that("app preserves a checkpoint directory created after startup", {
  skip_if_not_installed("shiny")
  skip_if_not_installed("dbscan")
  dir <- tempfile("app-collision-")
  on.exit(unlink(dir, recursive = TRUE))
  app <- gk_app(review = gk_app_test_review(), workdir = dir)
  shiny::testServer(app$serverFuncSource(), {
    session$setInputs(image = "img-1")
    dir.create(dir)
    writeLines("preserve this file", file.path(dir, "unrelated.txt"))
    session$setInputs(save_checkpoint = 1)
    expect_match(action_status(), "directory appeared")
    expect_identical(readLines(file.path(dir, "unrelated.txt")), "preserve this file")
    expect_false(file.exists(file.path(dir, "review.rds")))
  })
})

test_that("download archives verify and export inspection stays read-only", {
  skip_if_not_installed("shiny")
  skip_if_not_installed("dbscan")
  snap <- gk_lock(gk_app_test_review(), reviewer = "Reviewer One", status = "PENDING")
  archive <- tempfile(fileext = ".tar.gz")
  dest <- tempfile("app-extracted-")
  dir.create(dest)
  on.exit(unlink(c(archive, dest), recursive = TRUE))
  .gk_app_archive(snap, archive)
  members <- utils::untar(archive, list = TRUE)
  expect_true(all(startsWith(members, "review")))
  utils::untar(archive, exdir = dest)
  checks <- gk_verify_export(file.path(dest, "review"), strict = TRUE)
  expect_gt(nrow(checks), 0L)
  expect_true(all(checks$ok))
  app <- gk_app(export = file.path(dest, "review"))
  html <- as.character(app$httpHandler(list(PATH_INFO = "/", REQUEST_METHOD = "GET"))$content)
  expect_false(grepl('id="set_cut"', html, fixed = TRUE))
  shiny::testServer(app$serverFuncSource(), {
    session$setInputs(image = "img-1", reviewer = "Someone", reason = "Ignored", cut_estimate = 1, set_cut = 1,
      snapshot_status = "REVIEWED", confirm_reviewed = TRUE, lock_snapshot = 1)
    expect_null(current_review())
    expect_null(locked_snapshot())
    expect_match(output$overview, "Read-only inspection")
    expect_match(output$snapshot, "PENDING")
  })
})
